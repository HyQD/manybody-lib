"""Block-resolved closed-shell Hamiltonian construction."""

from __future__ import annotations

from fractions import Fraction
from functools import lru_cache
from itertools import product

from .expressions import Expression, Term
from .indices import OrbitalSpace, occupied, virtual
from .operators import OneBodyOperator, OperatorWord, TwoBodyOperator
from .reference import reference_expectation
from .tensors import TensorSymbol, simultaneous_column_symmetries


REFERENCE_ENERGY = TensorSymbol(
    "Eref",
    rank=0,
    latex_name=r"E_{\mathrm{ref}}",
)
FOCK = TensorSymbol("f", rank=2, upper_count=1)
TWO_ELECTRON = TensorSymbol(
    "u",
    rank=4,
    upper_count=2,
    symmetries=simultaneous_column_symmetries(2),
)


_INDEX_FACTORY = {
    OrbitalSpace.OCCUPIED: occupied,
    OrbitalSpace.VIRTUAL: virtual,
}


def _dummy(space: OrbitalSpace, name: str):
    return _INDEX_FACTORY[space](name, dummy=True)


@lru_cache(maxsize=1)
def build_effective_bare_hamiltonian() -> Expression:
    r"""Return the physical Hamiltonian expressed through ``f`` and ``u``.

    The spatial one-electron integrals have been eliminated with

    .. math::

        h^p_q=f^p_q-\sum_k\left(2u^{pk}_{qk}-u^{pk}_{kq}\right).

    General orbital sums are emitted explicitly as occupied/virtual blocks so
    that reference contractions never need an implicit occupation projector.
    """

    spaces = (OrbitalSpace.OCCUPIED, OrbitalSpace.VIRTUAL)
    terms = []

    for p_space, q_space in product(spaces, repeat=2):
        p = _dummy(p_space, "p")
        q = _dummy(q_space, "q")
        k = occupied("k", dummy=True)
        operator = OperatorWord((OneBodyOperator(p, q),))
        terms.extend(
            (
                Term(factors=(FOCK(p, q),), operators=operator),
                Term(
                    -2,
                    factors=(TWO_ELECTRON(p, k, q, k),),
                    operators=operator,
                ),
                Term(
                    factors=(TWO_ELECTRON(p, k, k, q),),
                    operators=operator,
                ),
            )
        )

    for block in product(spaces, repeat=4):
        indices = tuple(
            _dummy(space, name)
            for space, name in zip(block, "pqrs", strict=True)
        )
        terms.append(
            Term(
                Fraction(1, 2),
                factors=(TWO_ELECTRON(*indices),),
                operators=OperatorWord((TwoBodyOperator(*indices),)),
            )
        )

    return Expression.from_terms(terms)


@lru_cache(maxsize=1)
def build_normal_ordered_hamiltonian() -> Expression:
    r"""Return ``E_ref + H_N`` under the documented integral conventions.

    Subtracting the closed-shell expectation of the effective physical
    Hamiltonian is algebraically equivalent to reference normal ordering for
    the CI matrix elements generated by this engine.
    """

    bare = build_effective_bare_hamiltonian()
    reference = Expression.from_terms(
        (Term(factors=(REFERENCE_ENERGY(),)),)
    )
    return reference + bare - reference_expectation(bare)
